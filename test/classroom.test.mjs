import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { DatabaseSync } from 'node:sqlite';
import classroom from '../worker/classroom.ts';
import { issueTeacherAccess } from '../server/teacher-token.ts';

test('classroom accepts only the registered device; public reads expose only the latest reading', async t => {
  const db = new DatabaseSync(':memory:');
  t.after(() => db.close());
  db.exec(readFileSync(new URL('../schema.sql', import.meta.url), 'utf8'));
  const DB = { prepare: sql => ({ bind: (...args) => ({ first: async () => db.prepare(sql).get(...args) ?? null, run: async () => ({ meta: { changes: db.prepare(sql).run(...args).changes } }) }) }) };
  let now = Date.now();
  t.mock.method(Date, 'now', () => now);
  const TEACHER_PIN = crypto.randomUUID();
  const teacher = (await issueTeacherAccess(TEACHER_PIN)).token;
  const call = (path, method = 'GET', token, payload, room = 'pilot') => classroom.request(`/classrooms/${room}/${path}`, {
    method, headers: { ...(token && { Authorization: `Bearer ${token}` }), ...(payload && { 'Content-Type': 'application/json' }) }, body: payload ? JSON.stringify(payload) : undefined,
  }, { DB, TEACHER_PIN });
  const reading = (token, ppm = 1200, measuredAt = now) => call('device/reading', 'POST', token, { ppm, measuredAt });
  const latest = async () => (await call('latest')).json();
  const state = async () => (await call('teacher/state', 'GET', teacher)).json();
  assert.deepEqual(await latest(), { ppm: null, measuredAt: null, status: 'waiting' });
  assert.equal((await call('latest', 'GET', undefined, undefined, 'another')).status, 404);
  assert.equal((await call('teacher/device', 'POST')).status, 401);
  assert.equal((await call('teacher/state')).status, 401);
  assert.equal((await reading()).status, 401);
  assert.equal((await reading(`co2_${'a'.repeat(64)}`)).status, 401);
  const { token } = await (await call('teacher/device', 'POST', teacher)).json();
  assert.match(token, /^co2_[a-f0-9]{64}$/);
  assert.equal((await call('teacher/device', 'POST', teacher)).status, 409);
  assert.equal((await call('teacher/state', 'GET', token)).status, 401);
  assert.equal((await call('teacher/policy', 'PUT', teacher, { threshold: 1000, minutes: 1 })).status, 200);
  assert.equal((await call('device/reading', 'POST', token, { ppm: 1200, measuredAt: now, demo: true })).status, 400);
  assert.equal((await reading(token, 1200, now - 40_000)).status, 400);
  assert.equal((await reading(token)).status, 201);
  assert.equal((await reading(token)).status, 409);
  const start = now;
  assert.deepEqual(await latest(), { ppm: 1200, measuredAt: start, status: 'measuring' });
  assert.equal((await state()).warning, null);
  now += 30_000; assert.equal((await reading(token)).status, 201);
  assert.equal((await state()).warning, null);
  now += 30_000; assert.equal((await reading(token)).status, 201);
  assert.equal((await state()).warning, start);
  now += 30_000; assert.equal((await reading(token, 1250)).status, 201);
  assert.equal((await state()).warning, start);
  now += 90_001;
  assert.equal((await latest()).status, 'stopped');
  assert.equal((await state()).warning, null);
  assert.equal((await reading(token, 1250)).status, 201);
  assert.equal((await state()).warning, null);
  now += 30_000; assert.equal((await reading(token, 1000)).status, 201);
  assert.equal((await state()).warning, null);
  now += 90_001;
  assert.deepEqual(await latest(), { ppm: 1000, measuredAt: now - 90_001, status: 'stopped' });
  assert.equal((await reading(token)).status, 201);
  assert.equal((await state()).warning, null);
  assert.equal((await call('device/disconnect', 'POST', token)).status, 200);
  assert.equal((await latest()).status, 'stopped');
  now += 30_000; assert.equal((await reading(token)).status, 201);
  assert.equal((await latest()).status, 'measuring');
  assert.equal((await call('teacher/device', 'DELETE', teacher)).status, 200);
  assert.equal((await latest()).status, 'stopped');
  now += 30_000; assert.equal((await reading(token)).status, 401);
  const dbRow = db.prepare('SELECT * FROM classroom_live').all();
  assert.equal(dbRow.length, 1);
  assert.equal(dbRow[0].device_digest, null);
});
